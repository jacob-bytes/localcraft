/**
 * 全站页面容器的宽度与横向留白 —— **唯一来源**。
 *
 * 为什么要有这个常量：`max-w-[1400px]` 与那串响应式横向留白
 * （`px-4 sm:px-6 lg:px-8`）此前在 **8 个文件**里各写了一遍
 * （顶栏 / 页脚 / 两套布局 / 门户 / 详情 / 收藏 / 404 / 403）。
 * 逐字重复的后果不是"多打几个字"，而是**改一处漏七处**：
 * 想调内容宽度或窄屏留白，得先找齐 8 处，而没有任何东西会提醒你漏了哪一处。
 * `ToolDetailPage` 当时已经把它抽成了文件内的 `CONTAINER` 常量 —— 说明这个痛点
 * 已经被局部意识到，只是没跨文件共享。
 *
 * 为什么是常量而不是 `<Container>` 组件：这 8 处的**纵向留白与 display 各不相同**
 * （`py-6` / `py-16`、`flex-col` / `flex-row`、各自的 gap），抽成组件就得为它们开口子，
 * 反而把「一个宽度约定」变成一套 API。常量只固定**真正共享的那两件事**
 * （最大宽度 + 横向留白），其余留给各自站点。
 *
 * 与 `TOOL_PLACEHOLDER_CLASS` 同一套做法（`src/lib/toolMeta.ts`）：
 * Tailwind v4 从源码里扫类名字符串，常量定义处的字面量同样会被扫到，
 * 所以放在这里不会让这些工具类被裁掉。
 *
 * 注意：这里是**横向**留白，不含 `py-*`。纵向节奏是页面自己的事。
 */
export const PAGE_CONTAINER = "mx-auto w-full max-w-[1400px] px-4 sm:px-6 lg:px-8";
